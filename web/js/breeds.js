function sizeOf([lo, hi]) {
  const w = (lo + hi) / 2;
  if (w < 5) return 'mini';
  if (w < 10) return 'liten';
  if (w < 25) return 'middels';
  if (w < 45) return 'stor';
  return 'kjempe';
}

function b(id, name, dog, wiki, group, origin, weight, height, life, t, temperament, text) {
  const n = String(t).split('').map(Number);
  return {
    id, name, dog, wiki, group, origin, weight, height, life,
    size: sizeOf(weight),
    traits: { energy: n[0], grooming: n[1], kids: n[2], training: n[3], barking: n[4], shedding: n[5] },
    temperament: temperament.split(',').map((s) => s.trim()),
    text,
    banned: BANNED.includes(id),
  };
}

